import { test, expect } from '@playwright/test';

test('BHTN calculates, checks eligibility and reuses company sections under StrictMode', async ({ page }) => {
  const requests = new Map();
  page.on('request', request => {
    if (new URL(request.url()).pathname.startsWith('/api/')) requests.set(request.url(), (requests.get(request.url()) || 0) + 1);
  });
  await page.route('**/api/candidate/auth/me', route => route.fulfill({ status:401 }));
  await page.goto('/tools/unemployment-insurance');
  await expect(page.locator('.bhtn-total>strong')).toContainText('18.000.000');
  await expect(page.locator('.bhtn-result-stats')).toContainText('6.000.000');
  for (const selector of ['header','footer','.cv-templates','.career-knowledge','.career-tools']) await expect(page.locator(selector)).toHaveCount(1);
  await expect(page.getByRole('navigation',{name:'Đường dẫn'})).toContainText('Tính bảo hiểm thất nghiệp 2026');
  await page.getByRole('textbox',{name:'Lương bình quân 6 tháng',exact:true}).fill('100000000');
  await page.getByRole('button',{name:'144 tháng',exact:true}).click();
  await expect(page.locator('.bhtn-stale')).toBeVisible();
  await page.getByRole('button',{name:'TÍNH MỨC HƯỞNG BHTN NGAY',exact:true}).click();
  await expect(page.locator('.bhtn-result-stats')).toContainText('26.550.000');
  await expect(page.locator('.bhtn-total>strong')).toContainText('318.600.000');
  await expect(page.locator('.bhtn-formula')).toContainText('Đã áp dụng trần');
  await page.getByRole('checkbox',{name:'Nộp đủ hồ sơ trong 3 tháng từ ngày chấm dứt hợp đồng',exact:true}).uncheck();
  await page.getByRole('button',{name:'TÍNH MỨC HƯỞNG BHTN NGAY',exact:true}).click();
  await expect(page.locator('.bhtn-ineligible')).toContainText('Chưa xác nhận nộp đủ hồ sơ');
  await expect(page.locator('.bhtn-total>strong')).toHaveText('0 VND');
  await page.getByRole('checkbox',{name:'Nộp đủ hồ sơ trong 3 tháng từ ngày chấm dứt hợp đồng',exact:true}).check();
  await page.getByRole('textbox',{name:'Lương bình quân 6 tháng',exact:true}).fill('10000000');
  await page.getByRole('button',{name:'36 tháng',exact:true}).click();
  await page.getByRole('button',{name:'TÍNH MỨC HƯỞNG BHTN NGAY',exact:true}).click();
  await page.setViewportSize({width:1284,height:1000});
  await page.screenshot({path:'test-results/unemployment-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/unemployment-mobile.png',fullPage:true});
  for (const count of requests.values()) expect(count).toBe(1);
  expect([...requests.keys()].filter(url => !url.includes('/auth/me'))).toEqual([]);
  await expect(page.locator('.career-tools a[href="/tools/unemployment-insurance"]')).toHaveCount(1);
  await page.goto('/tools');
  await page.getByRole('link',{name:'Kiểm tra mức trợ cấp',exact:true}).click();
  await expect(page).toHaveURL(/\/tools\/unemployment-insurance$/);
});
