import {test,expect} from '@playwright/test';
test('BHXH periods, adjustment details, eligibility and shared resources work on desktop/mobile',async({page})=>{
  const requests=new Map();
  page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/')) requests.set(request.url(),(requests.get(request.url())||0)+1);});
  await page.route('**/api/candidate/auth/me',route=>route.fulfill({status:401}));
  await page.goto('/tools/social-insurance');
  await expect(page.locator('.bhxh-total>strong')).toContainText('45.087.000');
  await expect(page.locator('.bhxh-breakdown')).toContainText('6.441.000');
  for(const selector of ['header','footer','.cv-templates','.career-knowledge','.career-tools']) await expect(page.locator(selector)).toHaveCount(1);
  await page.getByText('Xem chi tiết điều chỉnh từng năm',{exact:true}).click();
  await expect(page.locator('.bhxh-yearly tbody tr')).toHaveCount(4);
  await page.getByRole('button',{name:'Thêm giai đoạn đóng BHXH mới',exact:true}).click();
  await page.getByLabel('Từ tháng giai đoạn 3',{exact:true}).fill('2022-04');
  await page.getByLabel('Đến tháng giai đoạn 3',{exact:true}).fill('2022-06');
  await page.getByRole('textbox',{name:'Mức lương giai đoạn 3',exact:true}).fill('6000000');
  await page.getByRole('button',{name:'TÍNH TIỀN BHXH 1 LẦN NGAY',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('trùng tháng');
  await page.getByRole('button',{name:'Xóa giai đoạn 3',exact:true}).click();
  await page.getByRole('checkbox',{name:'Tôi đã chấm dứt tham gia BHXH và xác nhận trường hợp đã chọn.',exact:true}).uncheck();
  await page.getByRole('button',{name:'TÍNH TIỀN BHXH 1 LẦN NGAY',exact:true}).click();
  await expect(page.locator('.bhxh-total>strong')).toHaveText('0 VND');
  await expect(page.locator('.bhxh-ineligible')).toContainText('Chưa xác nhận');
  await page.getByRole('checkbox',{name:'Tôi đã chấm dứt tham gia BHXH và xác nhận trường hợp đã chọn.',exact:true}).check();
  await page.getByRole('button',{name:'TÍNH TIỀN BHXH 1 LẦN NGAY',exact:true}).click();
  await expect(page.locator('.bhxh-stale')).toHaveCount(0);
  await page.setViewportSize({width:1284,height:1000});
  await page.screenshot({path:'test-results/social-insurance-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/social-insurance-mobile.png',fullPage:true});
  for(const count of requests.values()) expect(count).toBe(1);
  expect([...requests.keys()].filter(url=>!url.includes('/auth/me'))).toEqual([]);
  await expect(page.locator('.career-tools a[href="/tools/social-insurance"]')).toHaveCount(1);
  await page.goto('/tools');
  await page.getByRole('link',{name:'Ước tính BHXH 1 lần',exact:true}).click();
  await expect(page).toHaveURL(/\/tools\/social-insurance$/);
});
