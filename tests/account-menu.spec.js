import { test, expect } from '@playwright/test';
import { seedTokens, tokenSession } from './token-fixtures.js';

test('avatar menu shows account details, navigates and logs out on mobile', async ({ page }, testInfo) => {
  await seedTokens(page);
  await page.route('**/api/candidate/auth/me', route => route.fulfill({ json: { ...tokenSession().account, email: 'candidate@example.com' } }));
  await page.route('**/api/employer/auth/me', route => route.fulfill({ status: 401 }));
  await page.route('**/api/candidate/header', route => route.fulfill({ json: { messages: [], notifications: [] } }));
  await page.route('**/api/candidate/messages', route => route.fulfill({ json: [] }));
  await page.route('**/api/candidate/profile', route => route.fulfill({ json: { profile: { fullName: 'Test Candidate', experiences: [], skills: [], education: [], certificates: [], projects: [] }, cvs: [] } }));
  let logouts = 0;
  await page.route('**/api/candidate/auth/logout', route => {
    logouts += 1;
    expect(route.request().postDataJSON().refreshToken).toBe('test-refresh');
    return route.fulfill({ status: 204 });
  });
  await page.goto('/messages');
  const trigger = page.getByRole('button', { name: 'Tài khoản của Test Candidate', exact: true });
  await trigger.click();
  const menu = page.getByRole('menu', { name: 'Tài khoản của Test Candidate' });
  await expect(menu).toContainText('candidate@example.com');
  await expect(menu.getByRole('menuitem')).toHaveCount(3);
  await menu.screenshot({ path: testInfo.outputPath('account-menu-desktop.png') });
  await expect(menu.getByRole('menuitem', { name: 'Việc làm của tôi' })).toHaveAttribute('href', '/my-jobs');
  await page.keyboard.press('Escape');
  await expect(menu).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await page.keyboard.press('Enter');
  await menu.getByRole('menuitem', { name: 'Hồ sơ cá nhân' }).click();
  await expect(page).toHaveURL(/\/profile$/);
  await expect(page.getByRole('heading', { name: 'Test Candidate', exact: true })).toBeVisible();
  await expect(menu).toHaveCount(0);
  await page.setViewportSize({ width: 375, height: 812 });
  await trigger.click();
  const bounds = await menu.boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(375);
  await page.screenshot({ path: testInfo.outputPath('account-menu-mobile.png'), animations: 'disabled' });
  await menu.getByRole('menuitem', { name: 'Đăng xuất', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect(logouts).toBe(1);
  expect(await page.evaluate(() => sessionStorage.getItem('jobtot.candidate.tokens'))).toBeNull();
});
