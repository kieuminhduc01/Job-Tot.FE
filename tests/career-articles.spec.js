import { test, expect } from '@playwright/test';

test('admin drafts, previews and publishes content that candidates can read', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('jobtot.admin.session', JSON.stringify({accessToken:'admin',fullName:'Admin',expiresAt:'2099-01-01'})));
  await page.route('**/api/admin/auth/me', route => route.fulfill({json:{id:'admin',fullName:'Admin'}}));
  await page.route('**/api/candidate/auth/me', route => route.fulfill({status:401}));
  await page.route('**/api/employer/auth/me', route => route.fulfill({status:401}));
  let stored, initialGets = 0;
  await page.route('**/api/admin/career-articles**', route => {
    if (route.request().method() === 'GET') { initialGets++; return route.fulfill({json: stored ? [stored] : []}); }
    stored = {...route.request().postDataJSON(),id:'article-1',version:`v${initialGets}`,updatedAt:'2026-10-07T00:00:00Z'};
    return route.fulfill({json:stored});
  });
  const cover = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a5ZkAAAAASUVORK5CYII=', 'base64');
  await page.route('**/api/admin/career-articles/article-1/cover', route => {
    expect(route.request().headers()['content-type']).toContain('multipart/form-data');
    stored = { ...stored, coverUrl: '/uploads/articles/test.png', coverFileName: 'cover.png', coverContentType: 'image/png', coverSize: cover.length, version: 'cover-version' };
    return route.fulfill({ json: stored });
  });
  await page.route('**/uploads/articles/test.png', route => route.fulfill({ contentType: 'image/png', body: cover }));
  await page.route('**/api/career-articles', route => route.fulfill({json:stored?.published ? [stored] : []}));
  await page.route('**/api/career-articles/article-1', route => route.fulfill({json:stored}));
  await page.route('**/api/cv-templates', route => route.fulfill({json:[]}));
  await page.goto('/admin/career-articles');
  await expect(page.getByText('Chưa có bài viết. Chọn “Viết bài mới” để bắt đầu.')).toBeVisible();
  expect(initialGets).toBe(1);
  await page.getByRole('button',{name:'Viết bài mới'}).click();
  await page.getByLabel('Tiêu đề',{exact:true}).fill('Hướng dẫn viết CV');
  await page.getByLabel('Mô tả ngắn').fill('Giới thiệu kinh nghiệm thực tế.');
  await page.getByLabel('Ảnh bìa', { exact: true }).setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: cover });
  await expect(page.getByAltText('Xem trước ảnh bìa')).toBeVisible();
  const content = page.getByLabel('Nội dung', {exact:true});
  await content.fill('Thành tích');
  await content.selectText();
  await page.getByRole('button', {name:'Đậm',exact:true}).click();
  await expect(content).toHaveValue('**Thành tích**');
  await expect(page.locator('.markdown-preview strong')).toHaveText('Thành tích');
  await content.fill('| Kỹ năng | Mức độ |\n| --- | --- |\n| React | Tốt |\n\n[Job Tốt](https://example.com)\n\n- Kinh nghiệm');
  await expect(page.locator('.markdown-preview table')).toContainText('React');
  await expect(page.locator('.markdown-preview li')).toHaveText('Kinh nghiệm');
  await expect(page.locator('.markdown-preview a')).toHaveAttribute('href','https://example.com');
  await page.getByLabel('Nội dung',{exact:true}).fill('## Kinh nghiệm\n**Thành tích**\n<script>alert(1)</script>');
  await page.getByRole('button',{name:'Xem trước',exact:true}).click();
  await expect(page.locator('.article-body h2')).toHaveText('Kinh nghiệm');
  await expect(page.locator('.article-body')).toContainText('<script>alert(1)</script>');
  await page.getByRole('button',{name:'Lưu bài viết'}).click();
  await expect(page.locator('.app-toast-success')).toContainText('Đã lưu bản nháp.');
  expect(stored.published).toBe(false);
  expect(stored.coverUrl).toBe('/uploads/articles/test.png');
  await page.getByRole('combobox',{name:'Trạng thái',exact:true}).selectOption('published');
  await page.getByRole('button',{name:'Lưu bài viết'}).click();
  await expect.poll(() => stored.published).toBe(true);
  await expect(page.getByRole('button',{name:'Lưu bài viết'})).toBeEnabled();
  await page.goto('/cv-templates');
  await expect(page.locator('.knowledge-article-grid article')).toHaveCount(1);
  await expect(page.locator('.knowledge-cover img')).toHaveAttribute('src', '/uploads/articles/test.png');
  await page.locator('.knowledge-article-grid').getByRole('link',{name:'Khám phá ngay'}).click();
  await expect(page.getByRole('heading',{name:'Hướng dẫn viết CV',exact:true})).toBeVisible();
  await expect(page.locator('.article-body strong')).toHaveText('Thành tích');
  await page.getByRole('link',{name:'← Tất cả bài viết'}).click();
  await expect(page.locator('.article-catalog article')).toHaveCount(1);
});
